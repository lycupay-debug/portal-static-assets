export function formatResourceFileSize(size?: number | null) {
  if (size == null || !Number.isFinite(size) || size < 0) return ''
  if (size < 1024) return `${size} B`
  if (size < 1024 * 1024) return `${(size / 1024).toFixed(1)} KB`
  return `${(size / (1024 * 1024)).toFixed(1)} MB`
}

export function formatFileSize(size: number) { return size < 1024 * 1024 ? `${Math.max(1, Math.round(size / 1024))} KB` : `${(size / (1024 * 1024)).toFixed(1)} MB` }

export const resourceFileExtensions = new Set(['ppt', 'pptx', 'mp3', 'pdf', 'doc', 'docx', 'txt'])
